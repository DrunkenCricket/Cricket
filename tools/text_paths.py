"""Turn short slogans into SVG path data so ram art renders without any fonts installed
(the Worker's renderer has none). Run: python3 tools/text_paths.py > worker/textpaths.js"""
import json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
WORDS = ["WHOSE", "HOUSE", "RAMS", "RAMS HOUSE", "#1", "$", "D-FENSE", "ALL ACCESS", "MOM", "LA", "GO RAMS", "GOAT", "MVP", "99", "00", "12"]

f = TTFont(FONT)
gs, cmap, upm = f.getGlyphSet(), f.getBestCmap(), f["head"].unitsPerEm
out = {}
for word in WORDS:
    pen = SVGPathPen(gs)
    x = 0
    for ch in word:
        g = cmap.get(ord(ch))
        if not g:
            continue
        # flip y (fonts are y-up), 1 unit = 1/upm em, so size 1 em = 1 unit tall-ish
        gs[g].draw(TransformPen(pen, (1 / upm, 0, 0, -1 / upm, x / upm, 0)))
        x += gs[g].width
    out[word] = {"d": pen.getCommands(), "w": round(x / upm, 4)}
print("// Generated by tools/text_paths.py: slogan outlines (1 unit = font size), baseline at y=0.")
print("export const TEXT = " + json.dumps(out) + ";")
